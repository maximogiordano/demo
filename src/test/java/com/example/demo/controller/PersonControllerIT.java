package com.example.demo.controller;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.put;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import com.example.demo.entity.Person;
import com.example.demo.repository.PersonRepository;
import jakarta.validation.ConstraintViolationException;
import java.time.LocalDate;
import java.util.List;
import java.util.NoSuchElementException;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.data.core.PropertyReferenceException;
import org.springframework.http.MediaType;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.request.MockMvcRequestBuilders;

// Full application context against an in-memory H2 database in PostgreSQL mode, so the Flyway
// migrations, Hibernate schema validation and service-layer validation all run without Postgres.
@SpringBootTest(properties = {
    "spring.datasource.url=jdbc:h2:mem:demo;MODE=PostgreSQL;DB_CLOSE_DELAY=-1",
    "spring.datasource.username=sa",
    "spring.datasource.password="
})
@AutoConfigureMockMvc
class PersonControllerIT {

  @Autowired
  MockMvc mockMvc;

  @Autowired
  PersonRepository personRepository;

  // Never generated by the identity column, so it is always absent.
  static final long NONEXISTENT_ID = Long.MAX_VALUE;

  @AfterEach
  void cleanUp() {
    personRepository.deleteAll();
  }

  Person save(String firstName, String lastName, String dateOfBirth) {
    Person person = new Person();

    person.setFirstName(firstName);
    person.setLastName(lastName);
    person.setDateOfBirth(LocalDate.parse(dateOfBirth));

    return personRepository.save(person);
  }

  @Test
  void create() throws Exception {
    String body = """
        {
          "first_name": "MAX",
          "last_name": "JORDAN",
          "date_of_birth": "1978-10-26"
        }
        """;

    mockMvc.perform(post("/persons").contentType(MediaType.APPLICATION_JSON).content(body))
        .andExpect(status().isCreated())
        .andExpect(jsonPath("$.id").isNumber())
        .andExpect(jsonPath("$.first_name").value("MAX"))
        .andExpect(jsonPath("$.last_name").value("JORDAN"))
        .andExpect(jsonPath("$.date_of_birth").value("1978-10-26"));

    List<Person> persons = personRepository.findAll();

    assertEquals(1, persons.size());
    assertEquals("MAX", persons.get(0).getFirstName());
    assertEquals("JORDAN", persons.get(0).getLastName());
    assertEquals(LocalDate.parse("1978-10-26"), persons.get(0).getDateOfBirth());
  }

  @Test
  void createInvalid() throws Exception {
    String body = """
        {
          "last_name": "JORDAN"
        }
        """;

    mockMvc.perform(post("/persons").contentType(MediaType.APPLICATION_JSON).content(body))
        .andExpect(status().isBadRequest())
        .andExpect(jsonPath("$.type").value(ConstraintViolationException.class.getName()))
        .andExpect(jsonPath("$.description").value("the request body contains validation errors"));

    assertEquals(0, personRepository.count());
  }

  @Test
  void readById() throws Exception {
    Person person = save("MAX", "JORDAN", "1978-10-26");

    mockMvc.perform(get("/persons/{id}", person.getId()))
        .andExpect(status().isOk())
        .andExpect(jsonPath("$.id").value(person.getId()))
        .andExpect(jsonPath("$.first_name").value("MAX"))
        .andExpect(jsonPath("$.last_name").value("JORDAN"))
        .andExpect(jsonPath("$.date_of_birth").value("1978-10-26"));
  }

  @Test
  void readByIdNotFound() throws Exception {
    mockMvc.perform(get("/persons/{id}", NONEXISTENT_ID))
        .andExpect(status().isNotFound())
        .andExpect(jsonPath("$.type").value(NoSuchElementException.class.getName()))
        .andExpect(jsonPath("$.description").value("the given object does not exist"));
  }

  @Test
  void readPage() throws Exception {
    Person jordan = save("MAX", "JORDAN", "1978-10-26");
    Person adams = save("ANNA", "ADAMS", "1985-03-14");
    save("ZOE", "ZIMMER", "1990-07-01");

    mockMvc.perform(get("/persons").param("page", "0").param("size", "2")
            .param("sort", "lastName"))
        .andExpect(status().isOk())
        .andExpect(jsonPath("$.content.length()").value(2))
        .andExpect(jsonPath("$.content[0].id").value(adams.getId()))
        .andExpect(jsonPath("$.content[0].last_name").value("ADAMS"))
        .andExpect(jsonPath("$.content[1].id").value(jordan.getId()))
        .andExpect(jsonPath("$.content[1].last_name").value("JORDAN"))
        .andExpect(jsonPath("$.page.size").value(2))
        .andExpect(jsonPath("$.page.number").value(0))
        .andExpect(jsonPath("$.page.totalElements").value(3))
        .andExpect(jsonPath("$.page.totalPages").value(2));
  }

  @Test
  void readPageInvalidSort() throws Exception {
    mockMvc.perform(get("/persons").param("sort", "foo"))
        .andExpect(status().isBadRequest())
        .andExpect(jsonPath("$.type").value(PropertyReferenceException.class.getName()))
        .andExpect(jsonPath("$.description")
            .value("the sort param specifies a non-existent property"));
  }

  @Test
  void update() throws Exception {
    Person person = save("MAX", "JORDAN", "1978-10-26");

    String body = """
        {
          "first_name": "MICHAEL",
          "last_name": "JORDAN",
          "date_of_birth": "1963-02-17"
        }
        """;

    mockMvc.perform(put("/persons/{id}", person.getId())
            .contentType(MediaType.APPLICATION_JSON).content(body))
        .andExpect(status().isOk())
        .andExpect(jsonPath("$.id").value(person.getId()))
        .andExpect(jsonPath("$.first_name").value("MICHAEL"))
        .andExpect(jsonPath("$.last_name").value("JORDAN"))
        .andExpect(jsonPath("$.date_of_birth").value("1963-02-17"));

    Person updated = personRepository.findById(person.getId()).orElseThrow();

    assertEquals("MICHAEL", updated.getFirstName());
    assertEquals("JORDAN", updated.getLastName());
    assertEquals(LocalDate.parse("1963-02-17"), updated.getDateOfBirth());
  }

  @Test
  void updateNotFound() throws Exception {
    String body = """
        {
          "first_name": "MAX",
          "last_name": "JORDAN"
        }
        """;

    mockMvc.perform(put("/persons/{id}", NONEXISTENT_ID)
            .contentType(MediaType.APPLICATION_JSON).content(body))
        .andExpect(status().isNotFound())
        .andExpect(jsonPath("$.type").value(NoSuchElementException.class.getName()))
        .andExpect(jsonPath("$.description").value("the given object does not exist"));

    assertEquals(0, personRepository.count());
  }

  @Test
  void updateInvalid() throws Exception {
    Person person = save("MAX", "JORDAN", "1978-10-26");

    String body = """
        {
          "first_name": "MAX"
        }
        """;

    mockMvc.perform(put("/persons/{id}", person.getId())
            .contentType(MediaType.APPLICATION_JSON).content(body))
        .andExpect(status().isBadRequest())
        .andExpect(jsonPath("$.type").value(ConstraintViolationException.class.getName()))
        .andExpect(jsonPath("$.description").value("the request body contains validation errors"));

    assertEquals("JORDAN", personRepository.findById(person.getId()).orElseThrow().getLastName());
  }

  @Test
  void delete() throws Exception {
    Person person = save("MAX", "JORDAN", "1978-10-26");

    mockMvc.perform(MockMvcRequestBuilders.delete("/persons/{id}", person.getId()))
        .andExpect(status().isNoContent());

    assertFalse(personRepository.existsById(person.getId()));
  }

  // deleteById silently ignores missing ids, so deleting a nonexistent person still returns 204.
  @Test
  void deleteNotFound() throws Exception {
    mockMvc.perform(MockMvcRequestBuilders.delete("/persons/{id}", NONEXISTENT_ID))
        .andExpect(status().isNoContent());
  }

}
